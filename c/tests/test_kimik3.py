    def test_a_log_has_realistic_range(self):
        """KDA A_log (log retention factor) should be in a plausible range.

        A_log values are exp(-A) where A controls retention decay; typical
        range is [-1, 3]. This catches garbage bf16 reads (e.g. bit-flips
        would produce values like 1e30 or NaN)."""
        r = self._run_load_check()
        self.assertEqual(r.returncode, 0, r.stderr)
        line = [l for l in r.stdout.splitlines() if "self_attn.A_log" in l and "OK" in l][0]
        # Extract min/max from "min=X max=Y mean=Z"
        import re
        m = re.search(r"min=([+\-0-9.eE]+).*max=([+\-0-9.eE]+)", line)
        self.assertIsNotNone(m, f"could not parse min/max from: {line}")
        mn, mx = float(m.group(1)), float(m.group(2))
        self.assertGreater(mn, -10.0, f"A_log min {mn} implausibly negative")
        self.assertLess(mx, 10.0, f"A_log max {mx} implausibly large")
        self.assertNotEqual(mn, mx, "A_log all-same — likely misread as constant")

    def test_missing_tensors_reported_for_layers_not_downloaded(self):
        """Layers 1..92 are not downloaded, so they must be reported MISSING."""
        r = self._run_load_check()
        self.assertEqual(r.returncode, 0, r.stderr)
        summary = [l for l in r.stdout.splitlines() if "summary" in l][0]
        # We only downloaded layer 0 (23 tensors) + embed/head (5 tensors) = 28 OK.
        # The remaining tensors of layers 1..92 (each ~26 tensors x 92 layers + ...)
        # must be MISSING. We don't assert an exact count (it depends on which
        # layer types are checked), but it must be > 1000.
        import re
        m = re.search(r"MISSING=(\d+)", summary)
        self.assertIsNotNone(m, f"could not parse MISSING count: {summary}")
        missing = int(m.group(1))
        self.assertGreater(missing, 1000, f"too few MISSING tensors: {missing}")

    def test_deserialization_completes_with_ok_summary(self):
        """The very last line must confirm successful deserialization."""
        r = self._run_load_check()
        self.assertEqual(r.returncode, 0, r.stderr)
        last = r.stdout.strip().splitlines()[-1]
        self.assertIn("[OK]", last)
        self.assertIn("deserialization", last.lower())


