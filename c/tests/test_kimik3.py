"""Integration tests for the Kimi-K3 engine (kimik3.c).

Validates that the engine:
  - Builds cleanly (make kimik3)
  - Parses K3 config.json (nested text_config + linear_attn_config)
  - Loads both MXFP4-native and colibri-int8 expert snapshots
  - Runs end-to-end (MLA + KDA + Stable LatentMoE + dense MLP)
  - Produces deterministic output (same input -> same tokens twice)
  - Honours PPL=1 (teacher-forced NLL) mode
  - Reports expert cache hit/miss counters

The tiny K3 model is generated by tools/make_kimik3_tiny.py (no network, no
PyTorch) — 4 layers, 4 experts, hidden=64, vocab=256, MXFP4 packed experts.
The MXFP4 <-> int8 path is exercised by tools/convert_kimik3.py.

Run: python -m unittest tests.test_kimik3 -v
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

C_DIR = Path(__file__).resolve().parents[1]
ENGINE = C_DIR / "kimik3"
MAKE = shutil.which("make")
PY = sys.executable


def _run(cmd, env=None, cwd=None, timeout=120):
    """Run a command, return CompletedProcess. Throws on timeout."""
    return subprocess.run(
        cmd, cwd=cwd or C_DIR, env=env, text=True,
        capture_output=True, timeout=timeout,
    )


def _build_engine():
    """Ensure the kimik3 binary is built. Returns True on success."""
    if ENGINE.exists():
        # Force rebuild so we test current source, not a stale binary.
        _run([MAKE, "kimik3"])
    else:
        _run([MAKE, "kimik3"])
    return ENGINE.exists()


def _generate_tiny_model(out_dir):
    """Generate a tiny K3 model into out_dir. Idempotent per-out_dir."""
    if not (Path(out_dir) / "model.safetensors").exists():
        r = _run([PY, "tools/make_kimik3_tiny.py", "--out", str(out_dir)])
        if r.returncode != 0:
            raise RuntimeError(f"make_kimik3_tiny failed: {r.stderr}")
    return Path(out_dir)


def _run_engine(snap, cap=16, ref=None, extra_env=None, timeout=60):
    """Run ./kimik3 on a snapshot, return CompletedProcess."""
    env = dict(os.environ, SNAP=str(snap))
    if extra_env:
        env.update(extra_env)
    args = [str(ENGINE), str(cap)]
    if ref is not None:
        args.append(str(ref))
    return _run(args, env=env, timeout=timeout)


def _parse_engine_output(text):
    """Extract structured fields the engine prints to stdout."""
    out = {"raw": text}
    for line in text.splitlines():
        if line.startswith("[CFG]"):
            out.setdefault("cfg_lines", []).append(line)
        elif line.startswith("Reference:"):
            out["reference"] = [int(x) for x in line.split(":", 1)[1].split()]
        elif line.startswith("C engine :"):
            out["c_engine"] = [int(x) for x in line.split(":", 1)[1].split()]
        elif line.startswith("Matching tokens:"):
            num, den = line.split(":", 1)[1].strip().split("/")
            out["matching"] = (int(num), int(den))
        elif line.startswith("Expert cache hit rate:"):
            pct = float(line.split(":")[1].split("%")[0])
            out["hit_rate_pct"] = pct
            # extract (hit=N miss=M)
            tail = line.split("(hit=", 1)[1]
            h, m = tail.split(" miss=")
            out["hits"] = int(h); out["miss"] = int(m.rstrip(")"))
        elif line.startswith("PEAK RSS:"):
            out["peak_rss_gb"] = float(line.split(":")[1].strip().split()[0])
        elif line.startswith("Speed:"):
            out["tok_per_s"] = float(line.split(":")[1].split()[0])
        elif line.startswith("TF-NLL:"):
            # Format: "TF-NLL: %.4f nats/token over %d tokens  |  ppl = %.2f"
            parts = line.split()
            out["tf_nll"] = float(parts[1])
            out["tf_tokens"] = int(parts[4])  # "over <N> tokens"
            out["tf_ppl"] = float(parts[-1])
    return out


