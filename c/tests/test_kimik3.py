class KimiK3RealConfigTest(unittest.TestCase):
    """Validate the engine against the REAL Kimi-K3 config.json from Hugging Face.

    These tests prove the engine can parse the real K3 configuration and that
    every tensor name the engine expects to load actually exists in the real
    weight map (model.safetensors.index.json). Running the full 2.8T model
    requires ~1TB of storage and is out of scope for CI; config + tensor-name
    compatibility is the correct proxy for "can load real K3 weights".

    The real metadata lives at /workspace/k3_meta (downloaded from
    huggingface.co/moonshotai/Kimi-K3). If absent, tests are skipped.
    """

    REAL_META = Path("/workspace/k3_meta")

    @classmethod
    def setUpClass(cls):
        if not cls.REAL_META.exists():
            raise unittest.SkipTest(f"real K3 metadata not found at {cls.REAL_META}")
        if not _build_engine():
            raise unittest.SkipTest("kimik3 build failed")
        with open(cls.REAL_META / "config.json") as f:
            cls.cfg = json.load(f)
        with open(cls.REAL_META / "model.safetensors.index.json") as f:
            cls.idx = json.load(f)
        cls.weight_map = cls.idx["weight_map"]

    def _run_config_check(self):
        env = dict(os.environ, SNAP=str(self.REAL_META))
        return _run([str(ENGINE), "--config-check"], env=env, timeout=30)

    def test_config_check_exits_zero(self):
        """--config-check must parse the real config.json without error."""
        r = self._run_config_check()
        self.assertEqual(r.returncode, 0, r.stderr)

    def test_real_config_dimensions(self):
        """Engine reports the exact dimensions from the real K3 config.json."""
        r = self._run_config_check()
        self.assertEqual(r.returncode, 0, r.stderr)
        out = _parse_engine_output(r.stdout)
        cfg1 = out["cfg_lines"][0]
        tc = self.cfg["text_config"]
        self.assertIn(f"hidden={tc['hidden_size']}", cfg1)
        self.assertIn(f"layers={tc['num_hidden_layers']}", cfg1)
        self.assertIn(f"experts={tc['num_experts']}", cfg1)
        self.assertIn(f"topk={tc['num_experts_per_token']}", cfg1)
        self.assertIn(f"shared={tc['num_shared_experts']}", cfg1)
        self.assertIn(f"vocab={tc['vocab_size']}", cfg1)

    def test_real_config_attention_dims(self):
        """Engine reports the exact MLA/KDA attention dimensions."""
        r = self._run_config_check()
        self.assertEqual(r.returncode, 0, r.stderr)
        out = _parse_engine_output(r.stdout)
        cfg2 = out["cfg_lines"][1]
        tc = self.cfg["text_config"]
        self.assertIn(f"q_lora={tc['q_lora_rank']}", cfg2)
        self.assertIn(f"kv_lora={tc['kv_lora_rank']}", cfg2)
        self.assertIn(f"qk_nope={tc['qk_nope_head_dim']}", cfg2)
        self.assertIn(f"qk_rope={tc['qk_rope_head_dim']}", cfg2)
        self.assertIn(f"v_head={tc['v_head_dim']}", cfg2)
